# String Slicing

name = "ABHAY RAJ"

print(name[0:2])
print(name[0:4])
print(name[0:4:2])
print(name[0:9:2])      # every second character
print(name[::2])      # every second character

print(name[-2:])        # last two character
print(name[::-1])       # string reverse
print(name[-3:])        # last three character
print(name[0:-5])       # prints upto -5


