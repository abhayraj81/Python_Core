# Strings Operators

a = " Hello !"
b = " Raj"

print(a+b)   # concatenate
print(a*2)   # multiple copies

# in operator (membership operator)
if "H" in a :
    print("yes")
else:
    print("Noo")
# not in operator (membership operator)
if "H" not in a :
    print("yes")
else:
    print("Noo")

# r/R 
print(r"Hello!\nWorld") # raw string : supresses the escape character
