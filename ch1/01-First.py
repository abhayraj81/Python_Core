# Simple Print Statement
print("Hello World!")

# Print Using Passing Variable
name = "Abhay Raj"
print(name)
print("Hello !",name)
print("Hello !" , name, sep=" - ")  #using separators (we can pass any relevant separator)

# Printing Int and Float
print(5)
print(2.8)
print("5+3") #inside quotes treated as string

# Printing Mathematical Expression Directly
print(2+9)

# Printing Mathematical Expression using variable method
a = 2
b = 9
sum = a+b
print(sum)

# Note : String are always written in Double Quotes whereas numerical values can be written directly