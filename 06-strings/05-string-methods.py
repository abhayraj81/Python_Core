#   String Methods

name = "Abhay Raj from AllenHouse"

# len() - returns length
print(len(name))    

# upper() - returns all character in upper case
print(name.upper())

# lower() - returns all character in lower case
print(name.lower())

# count() - returns no.s of character count in string
print(name.count('a'))

# find() - return index value of chracter
print(name.find("f"))

# split() - 
print(name.split())

# replace(old,new) - 
print(name.replace("Abhay","Anshika"))

# title() - captalized every next word in the string
print(name.title())

# strip() - removes white spaces / trailing spaces
word = "   Hello ! Abhay   "
print(word)
print(len(word))
print(word.strip())

# join() - 
zword = ("Abhay","is","great","have","fun.")
print(" ".join(zword))
print("-".join(zword))
print("_".join(zword))





 



   